#include "jitter_csv.h"

#include <inttypes.h>
#include <stdio.h>

int write_jitter_csv(const char *path, const int64_t *jitter_ns, size_t count)
{
    FILE *fp;
    size_t i;

    fp = fopen(path, "w");
    if (fp == NULL) {
        perror("fopen");
        return -1;
    }

    if (fprintf(fp, "n,jitter_ns\n") < 0) {
        perror("fprintf");
        fclose(fp);
        return -1;
    }

    for (i = 0; i < count; i++) {
        if (fprintf(fp, "%zu,%" PRId64 "\n", i, jitter_ns[i]) < 0) {
            perror("fprintf");
            fclose(fp);
            return -1;
        }
    }

    if (fclose(fp) != 0) {
        perror("fclose");
        return -1;
    }

    return 0;
}
